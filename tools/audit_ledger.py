"""Progress ledger for the 146-item improvement audit.

Source of truth:
  docs/backlog/items.json    the 146 audit items (imported once from the audit document)
  docs/backlog/status.json   status, evidence, tests, commits and blockers per item
  docs/backlog/CONTINUE.md   hand-written continuation notes, included verbatim in the report
Rendered report (do not edit by hand):
  docs/AUDIT_146_PROGRESS.md

Usage:
  python tools/audit_ledger.py import <audit.md>     # one-time import of the item list
  python tools/audit_ledger.py set 040 COMPLETE --evidence "..." [--tests "..."] [--commits "abc123"] [--needs "..."]
  python tools/audit_ledger.py render
  python tools/audit_ledger.py check                 # used by CI: all items accounted for, report up to date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ITEMS_FILE = ROOT / "docs" / "backlog" / "items.json"
STATUS_FILE = ROOT / "docs" / "backlog" / "status.json"
CONTINUE_FILE = ROOT / "docs" / "backlog" / "CONTINUE.md"
REPORT_FILE = ROOT / "docs" / "AUDIT_146_PROGRESS.md"

STATUSES = ("COMPLETE", "PARTIAL", "MISSING", "NOT APPLICABLE")
ITEM_RE = re.compile(r"^- \[[ x]\] \*\*(\d{3}) · (P\d) · (observed|recommended)\*\* — (.+)$")
SECTION_RE = re.compile(r"^## (\d+)\. (.+?) — (P\d)$")


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _save(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(payload, indent=1, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8"))


def import_items(audit_path: Path) -> int:
    sections: list[dict] = []
    items: dict[str, dict] = {}
    for line in audit_path.read_text(encoding="utf-8").splitlines():
        section = SECTION_RE.match(line.strip())
        if section:
            sections.append({"number": int(section[1]), "title": section[2], "priority": section[3]})
            continue
        item = ITEM_RE.match(line.strip())
        if item and sections:
            items[item[1]] = {"priority": item[2], "kind": item[3], "section": sections[-1]["number"], "text": item[4]}
    _save(ITEMS_FILE, {"sections": sections, "items": items})
    return len(items)


def set_status(item_id: str, status: str, evidence: str, tests: str, commits: str, needs: str | None) -> None:
    items = _load(ITEMS_FILE)["items"]
    if item_id not in items:
        raise SystemExit(f"Unknown item {item_id}")
    if status not in STATUSES:
        raise SystemExit(f"Status must be one of {STATUSES}")
    statuses = _load(STATUS_FILE)
    entry = dict(statuses.get(item_id, {}))
    entry["status"] = status
    if evidence:
        entry["evidence"] = evidence
    if tests:
        entry["tests"] = tests
    if commits:
        known = [c for c in str(entry.get("commits", "")).split(", ") if c]
        entry["commits"] = ", ".join(dict.fromkeys(known + [c.strip() for c in commits.split(",") if c.strip()]))
    if needs is not None:
        if needs:
            entry["needs"] = needs
        else:
            entry.pop("needs", None)
    statuses[item_id] = entry
    _save(STATUS_FILE, statuses)


def render() -> str:
    data = _load(ITEMS_FILE)
    statuses = _load(STATUS_FILE)
    sections, items = data["sections"], data["items"]
    counts = Counter(statuses.get(item_id, {}).get("status", "MISSING") for item_id in items)
    lines = [
        "# Audit backlog: progress on all 146 items",
        "",
        "Generated by `tools/audit_ledger.py` from `docs/backlog/items.json` and `docs/backlog/status.json`. "
        "Do not edit this file by hand; use `python tools/audit_ledger.py set ...` and `render`.",
        "",
        "A status is **COMPLETE** only when a real implementation exists and was verified as described under "
        "*Tests*. A placeholder, a mock, a setting or a document alone does not count. **PARTIAL** means real "
        "work exists but the item's full intent is not met; the evidence says what is missing.",
        "",
        "## Summary",
        "",
        "| Status | Items |",
        "|---|---|",
    ]
    lines += [f"| {status} | {counts.get(status, 0)} |" for status in STATUSES]
    lines += [f"| **Total** | **{len(items)}** |", "", "| Section | Complete | Partial | Missing | N/A |", "|---|---|---|---|---|"]
    for section in sections:
        ids = [item_id for item_id, item in items.items() if item["section"] == section["number"]]
        per = Counter(statuses.get(item_id, {}).get("status", "MISSING") for item_id in ids)
        lines.append(
            f"| {section['number']}. {section['title']} ({section['priority']}) | {per.get('COMPLETE', 0)} | "
            f"{per.get('PARTIAL', 0)} | {per.get('MISSING', 0)} | {per.get('NOT APPLICABLE', 0)} |"
        )
    lines += ["", "## How to continue", ""]
    lines += (CONTINUE_FILE.read_text(encoding="utf-8").strip().splitlines() if CONTINUE_FILE.exists() else ["No notes yet."])
    blocked = [(item_id, statuses[item_id]) for item_id in sorted(items) if statuses.get(item_id, {}).get("needs")]
    lines += ["", "## Items that need the owner", "", "Hardware, credentials, paid services or approval that this work could not supply.", ""]
    lines += [f"- **{item_id}** ({entry['status']}): {entry['needs']}" for item_id, entry in blocked] or ["None."]
    for section in sections:
        lines += ["", f"## {section['number']}. {section['title']} ({section['priority']})", ""]
        for item_id in sorted(items):
            item = items[item_id]
            if item["section"] != section["number"]:
                continue
            entry = statuses.get(item_id, {})
            lines += [f"### {item_id} · {item['priority']} · {item['kind']} · {entry.get('status', 'MISSING')}", "", f"> {item['text']}", ""]
            lines.append(f"- **Evidence:** {entry.get('evidence', 'Not examined yet.')}")
            if entry.get("tests"):
                lines.append(f"- **Tests:** {entry['tests']}")
            if entry.get("commits"):
                lines.append(f"- **Commits:** {entry['commits']}")
            if entry.get("needs"):
                lines.append(f"- **Needs:** {entry['needs']}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def check() -> list[str]:
    data = _load(ITEMS_FILE)
    statuses = _load(STATUS_FILE)
    problems = []
    if len(data.get("items", {})) != 146:
        problems.append(f"expected 146 items, found {len(data.get('items', {}))}")
    for item_id in sorted(data.get("items", {})):
        entry = statuses.get(item_id)
        if not entry:
            problems.append(f"{item_id}: no status recorded")
        elif entry.get("status") not in STATUSES:
            problems.append(f"{item_id}: invalid status {entry.get('status')!r}")
        elif not entry.get("evidence"):
            problems.append(f"{item_id}: no evidence recorded")
        elif entry["status"] == "COMPLETE" and not entry.get("tests"):
            problems.append(f"{item_id}: COMPLETE without a description of how it was verified")
    if not REPORT_FILE.exists() or REPORT_FILE.read_text(encoding="utf-8") != render():
        problems.append("docs/AUDIT_146_PROGRESS.md is out of date; run: python tools/audit_ledger.py render")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("import").add_argument("audit")
    setter = sub.add_parser("set")
    setter.add_argument("item")
    setter.add_argument("status", choices=STATUSES)
    setter.add_argument("--evidence", default="")
    setter.add_argument("--tests", default="")
    setter.add_argument("--commits", default="")
    setter.add_argument("--needs", default=None)
    sub.add_parser("render")
    sub.add_parser("check")
    args = parser.parse_args()

    if args.command == "import":
        print(f"imported {import_items(Path(args.audit))} items")
    elif args.command == "set":
        set_status(args.item, args.status, args.evidence, args.tests, args.commits, args.needs)
    if args.command in {"set", "render"}:
        REPORT_FILE.write_bytes(render().encode("utf-8"))
        print(f"rendered {REPORT_FILE.relative_to(ROOT)}")
    if args.command == "check":
        problems = check()
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
